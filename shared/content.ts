function expand(group: Group): Content[] {
  const additions: Record<string, string[]> = {
    'Attirance, curiosité et personnes présentes': morePeople,
    'Confessions et questions embarrassantes': moreConfessions,
    'Secrets, mensonges et grosses bêtises': moreSecrets,
    'Anecdotes personnelles et souvenirs': moreAnecdotes,
    'Amitiés, affinités et premières impressions': moreFriendships,
    'Personnalité, habitudes et caractère': morePersonality,
    'Questions inattendues et provocantes': moreUnexpected,
    'Défis drôles et embarrassants': moreFunnyActions,
    'Défis photo et objets': morePhotoActions,
    'Imitations et improvisations': moreImitations,
    'Découverte de la personnalité': morePersonalityActions,
    'Missions spéciales BLACKOPS': moreMissions,
    'Créativité et cadeaux virtuels': moreCreativeActions
  };
  const prompts = [...group.prompts, ...(additions[group.category] || [])];
  const levelFor = (index: number): 1 | 2 | 3 => {
    if (group.kind === 'action') return group.category === 'Missions spéciales BLACKOPS' ? (index % 3 === 0 ? 3 : 2) : (index % 4 === 0 ? 2 : 1);
    if (group.category === 'Attirance, curiosité et personnes présentes') return index % 3 === 0 ? 3 : 2;
    if (group.category === 'Secrets, mensonges et grosses bêtises') return index % 4 === 0 ? 3 : 2;
    if (group.category === 'Confessions et questions embarrassantes') return index % 5 === 0 ? 3 : index % 2 === 0 ? 2 : 1;
    if (group.category === 'Questions inattendues et provocantes') return index % 6 === 0 ? 3 : index % 3 === 0 ? 2 : 1;
    return index % 4 === 0 ? 2 : 1;
  };
  const rows = prompts.map((prompt, index): Content => ({
    id: `${group.kind[0]}-${[...truths, ...actions].findIndex(g => g.category === group.category) + 1}-${String(index + 1).padStart(3, '0')}`,
    kind: group.kind, category: group.category,
    level: levelFor(index),
    text: prompt,
    photo: group.category === 'Défis photo et objets',
    gift: group.category === 'Créativité et cadeaux virtuels',
    timer: group.category === 'Missions spéciales BLACKOPS' && prompt.includes('EXPRESS') ? 60 : undefined
  }));
  if (rows.length !== group.count) throw new Error(`Contenu insuffisant : ${group.category} (${rows.length}/${group.count})`);
  return rows;
}
